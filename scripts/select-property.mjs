#!/usr/bin/env node
/**
 * Selects the property this build serves and generates `src/generated/property.ts`.
 *
 * The generated module uses static imports so the bundler traces the property's
 * JSON into the standalone output — a runtime `fs` read of a path built from an
 * env var would not be traced, and would break in the Docker image.
 *
 * Usage: PROPERTY=<slug> node scripts/select-property.mjs
 * With a single directory under `properties/`, PROPERTY may be omitted.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validatePropertyConfig } from "./validate-property.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROPERTIES_DIR = join(ROOT, "properties");
const THEMES_DIR = join(ROOT, "src", "themes");
const OUTPUT_FILE = join(ROOT, "src", "generated", "property.ts");
const THEME_OUTPUT_FILE = join(ROOT, "src", "generated", "theme.ts");
const SCHEMA_FILE = join(PROPERTIES_DIR, "schema.json");

function fail(message) {
  console.error(`[select-property] ${message}`);
  process.exit(1);
}

function listProperties() {
  if (!existsSync(PROPERTIES_DIR)) {
    fail(`No properties/ directory at ${PROPERTIES_DIR}.`);
  }

  return readdirSync(PROPERTIES_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function resolveSlug() {
  const available = listProperties();
  const requested = process.env.PROPERTY?.trim();

  if (!requested) {
    if (available.length === 1) return available[0];
    fail(
      available.length === 0
        ? "properties/ is empty — add properties/<slug>/property.config.json."
        : `PROPERTY is not set and properties/ holds several: ${available.join(", ")}.`
    );
  }

  if (!available.includes(requested)) {
    fail(`Unknown property "${requested}". Available: ${available.join(", ") || "none"}.`);
  }

  return requested;
}

function validate(config, slug) {
  // Single source of truth: properties/schema.json, interpreted by the shared
  // validator so build-time and runtime checks can never drift apart.
  const schema = JSON.parse(readFileSync(SCHEMA_FILE, "utf8"));
  const errors = validatePropertyConfig(config, schema);

  if (errors.length > 0) {
    fail(`properties/${slug}/property.config.json is invalid:\n  - ${errors.join("\n  - ")}`);
  }

  if (config.slug !== slug) {
    fail(`properties/${slug}/property.config.json declares slug "${config.slug}".`);
  }

  const themeDir = join(THEMES_DIR, config.theme);
  if (!existsSync(themeDir) || !existsSync(join(themeDir, "index.ts"))) {
    const available = existsSync(THEMES_DIR)
      ? readdirSync(THEMES_DIR, { withFileTypes: true })
          .filter((entry) => entry.isDirectory())
          .map((entry) => entry.name)
          .sort()
      : [];
    fail(
      `properties/${slug}/property.config.json selects unknown theme "${config.theme}". ` +
        `Available: ${available.join(", ") || "none"}.`
    );
  }
}

function findMessageLocales(slug) {
  const messagesDir = join(PROPERTIES_DIR, slug, "messages");

  if (!existsSync(messagesDir)) return [];

  return readdirSync(messagesDir)
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.replace(/\.json$/, ""))
    .sort();
}

function generate(slug, locales) {
  const base = `../../properties/${slug}`;
  const imports = locales
    .map((locale) => `import messages_${locale} from "${base}/messages/${locale}.json";`)
    .join("\n");
  const entries = locales.map((locale) => `  ${locale}: messages_${locale},`).join("\n");

  return `// AUTO-GENERATED by scripts/select-property.mjs — do not edit.
// Regenerate with: PROPERTY=${slug} node scripts/select-property.mjs
import type { PropertyConfig, PropertyMessages } from "@/shared/property/types";
import config from "${base}/property.config.json";
${imports}

export const propertyConfig: PropertyConfig = config;

export const propertyMessages: PropertyMessages = {
${entries}
};
`;
}

function generateTheme(theme) {
  return `// AUTO-GENERATED by scripts/select-property.mjs — do not edit.
// The selected theme is build-time static so Next.js can analyze every route.
export {
  AboutPage,
  BlogDetailPage,
  BlogPage,
  CheckoutPage,
  CheckoutSuccessPage,
  ContactPage,
  FaqPage,
  HomePage,
  ProductDetailPage,
  ProductsPage,
  generateAboutMetadata,
  generateBlogDetailMetadata,
  generateBlogMetadata,
  generateCheckoutMetadata,
  generateContactMetadata,
  generateFaqMetadata,
  generateHomeMetadata,
  generateProductDetailMetadata,
  generateProductsMetadata,
} from "@/themes/${theme}";
`;
}

const slug = resolveSlug();
const configPath = join(PROPERTIES_DIR, slug, "property.config.json");

if (!existsSync(configPath)) {
  fail(`Missing ${configPath}.`);
}

let config;

try {
  config = JSON.parse(readFileSync(configPath, "utf8"));
} catch (error) {
  fail(`Could not parse ${configPath}: ${error.message}`);
}

validate(config, slug);

const locales = findMessageLocales(slug);
const output = generate(slug, locales);
const themeOutput = generateTheme(config.theme);

mkdirSync(dirname(OUTPUT_FILE), { recursive: true });

// Only write when the content changes, so a dev server watching this file does
// not reload on every `npm run dev`.
if (!existsSync(OUTPUT_FILE) || readFileSync(OUTPUT_FILE, "utf8") !== output) {
  writeFileSync(OUTPUT_FILE, output);
}

if (
  !existsSync(THEME_OUTPUT_FILE) ||
  readFileSync(THEME_OUTPUT_FILE, "utf8") !== themeOutput
) {
  writeFileSync(THEME_OUTPUT_FILE, themeOutput);
}

console.log(
  `[select-property] ${slug} (${config.domain}) — theme: ${config.theme}; message overrides: ${
    locales.join(", ") || "none"
  }`
);
